#!/usr/bin/env python3
"""Zero-RPC Stage-1 proxy and honest proxy/NetCover correlation contracts.

The proxy consumes only fields already returned by the free DefiLlama pool
feed (plus ``fee_tier`` parsed locally from its ``poolMeta`` string).  It is a
lead-ranking model, never an entry gate.  Terminal NetCover remains the sole
economic gate and missing proxy evidence fails closed to the APR fallback.

The M1 position is fixed at 50 USD.  Position size is deliberately not an
optimisation/ranking feature: audit evidence shows fee tier and holding horizon,
not larger capital, dominate the fixed round-trip drag.
"""
from __future__ import annotations

